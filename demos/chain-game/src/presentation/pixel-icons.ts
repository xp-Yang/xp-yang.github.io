export type PixelIconName = keyof typeof PATTERNS;

function pixels(name: PixelIconName, draw: (x: number, y: number, width: number) => void): void {
  PATTERNS[name].forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] !== '#') continue;
      const start = x;
      while (row[x + 1] === '#') x += 1;
      draw(start, y, x - start + 1);
    }
  });
}

export function pixelIcon(name: PixelIconName): string {
  let path = '';
  pixels(name, (x, y, width) => { path += `M${x} ${y}h${width}v1h-${width}z`; });
  return `<svg class="hud-icon pixel-art" viewBox="0 0 16 16" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true"><path d="${path}"/></svg>`;
}

export function drawPixelIcon(
  ctx: CanvasRenderingContext2D,
  name: PixelIconName,
  x: number,
  y: number,
  scale: number,
  color: string,
): void {
  ctx.fillStyle = color;
  pixels(name, (px, py, width) => {
    ctx.fillRect(x + px * scale, y + py * scale, width * scale, scale);
  });
}
